const STORE_KEY = 'loyalty-lang';

function detect() {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved && D[saved]) return saved;
  } catch { /* ignore */ }
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('zh')) return 'zh';
  if (nav.startsWith('ms') || nav.startsWith('id')) return 'ms';
  return 'en';
}

export let lang = detect();

export function setLang(code) {
  if (!D[code]) return;
  lang = code;
  try { localStorage.setItem(STORE_KEY, code); } catch { /* ignore */ }
  document.documentElement.lang = code === 'zh' ? 'zh-Hans' : code;
}
setLang(lang);

export function t(key, vars) {
  let s = D[lang][key] ?? D.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

const LOCALES = { en: 'en-MY', ms: 'ms-MY', zh: 'zh-CN' };

export function fmtDate(ts, opts = { day: 'numeric', month: 'short', year: 'numeric' }) {
  if (!ts) return '';
  return new Intl.DateTimeFormat(LOCALES[lang], opts).format(new Date(ts));
}

export function fmtDateTime(ts) {
  return fmtDate(ts, { day: 'numeric', month: 'short', year: 'numeric', hour: 'numeric', minute: '2-digit' });
}

export function fmtMoney(n, cur) {
  const v = Number(n) || 0;
  return `${cur}${v.toLocaleString(LOCALES[lang], { minimumFractionDigits: v % 1 ? 2 : 0, maximumFractionDigits: 2 })}`;
}

export function relDay(ts, now = Date.now()) {
  if (!ts) return t('never');
  const a = new Date(ts); a.setHours(0, 0, 0, 0);
  const b = new Date(now); b.setHours(0, 0, 0, 0);
  const n = Math.round((b - a) / 864e5);
  if (n <= 0) return t('today');
  if (n === 1) return t('yesterday');
  return t('daysAgo', { n });
}
